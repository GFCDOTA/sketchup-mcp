"""FP-054 F0 — inventario reconciliado, grafo de dependencias e varredura de riscos. Somente leitura: mede, nao conserta.

    python -m tools.navigation.baseline_inventory --out docs/reports/fp054/f0     # inventory.csv + grafo + hazards
    python -m tools.navigation.baseline_inventory --summary                      # so as contagens

Reaproveita `tools.navigation.file_audit` (estado/razao de cada arquivo, imports Python, citacoes) e acrescenta:

- **classe** de cada arquivo versionado (codigo ativo/inalcancado, teste, contrato, fixture, fonte, conhecimento, artefato,
  legado, documentacao, gerado, configuracao, instrucao de agente, asset) — nenhum fica sem classe; a soma bate com
  `git ls-files` no commit (`inventory_summary.json: reconciled`);
- **matriz** arquivo -> owner -> especialista (perfil do comodo + fragmento dono) -> capacidades do catalogo -> testes que o
  importam -> achados da varredura;
- **grafo**: imports Python (topo e tardios), referencias Python -> Ruby, `require`/`load` Ruby, tools MCP -> modulos que
  chamam, passos do CI -> modulo executado;
- **varredura** (`hazards.json`): except silencioso/amplo, `noqa`, skip/xfail, `global`, caches de modulo, `sys.path` em
  import, leitura de ambiente, constantes de escala fora de `core/scale.py`, constantes duplicadas entre modulos e
  semantica por nome (`module`/`name` comparado com texto).

Complexidade: O(A + T) tempo e espaco, A = arquivos versionados, T = bytes de texto lidos (cada arquivo e lido e parseado
uma vez; citacoes por indice de tokens do `file_audit`). Determinismo: toda saida ordenada; nada depende de relogio.
"""
